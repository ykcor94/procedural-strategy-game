  await page.waitForFunction(()=>window.atlas?.world&&!atlas.busy,null,{timeout:180000});
  console.log('Global generation',await page.locator('#status').innerText());
  assert.equal(await page.evaluate(()=>atlas.world.version),3);
  assert.ok(await page.evaluate(()=>atlas.world.layers.annualIce.some(v=>v>0)));
  await ready();console.log('Global LOD',await page.evaluate(()=>atlas.renderer.detailStatus));
  await page.screenshot({path:'test-output/v2-global-light.png'});
  if(await page.evaluate(()=>document.documentElement.dataset.theme!=='dark'))await page.click('#theme-toggle');
  assert.equal(await page.evaluate(()=>localStorage.getItem('atlas-theme')),'dark');
  await page.screenshot({path:'test-output/v2-global-dark.png'});
  const global=await page.evaluate(()=>{const l=atlas.world.layers,w=atlas.world.width,h=atlas.world.height;let i=l.elevation.findIndex((e,k)=>e>400&&e<2400&&l.riverDistance[k]>3&&l.annualTemperature[k]>10&&Math.floor(k/w)>h*.25&&Math.floor(k/w)<h*.75);const c=atlas.renderer.camera;c.x=i%w+.5;c.y=Math.floor(i/w)+.5;c.zoom(18);atlas.renderer.draw();return {i,e:l.elevation[i],mean:atlas.world.meta.statistics.meanTemperature};});
  await page.screenshot({path:'test-output/v2-regional-fallback.png'});
  await ready();console.log('Regional LOD',await page.evaluate(()=>atlas.renderer.detailStatus));
  assert.ok(await page.evaluate(()=>atlas.renderer.detailStatus.level>=4));
  assert.ok(await page.evaluate(()=>atlas.renderer.tiles.cache.bytes<=64*1024*1024));
  await page.screenshot({path:'test-output/v2-regional.png'});
  await openLayers(page).then(()=>page.check('#overlay-valleys'));await ready();
  await page.screenshot({path:'test-output/v2-valleys.png'});
  const generation=await page.evaluate(()=>atlas.renderer.tiles.generation);
  await page.click('#toggle-edit');await page.selectOption('#edit-scope','detail');await page.click('[data-tool="raise"]');
  const box=await page.locator('#map').boundingBox();
  const sample=()=>page.evaluate(()=>{const c=atlas.renderer.camera,p=c.toWorld(c.width/2,c.height/2);return atlas.renderer.sampleElevation(((p.x/atlas.world.width)%1+1)%1,p.y/atlas.world.height);});
  const before=await sample();
  await page.mouse.click(box.x+box.width/2,box.y+box.height/2);
  await page.waitForFunction(()=>atlas.world.meta.detail.edits.length===1);await ready();
  assert.ok(await sample()>before+100);
  assert.equal(await page.evaluate(i=>atlas.world.layers.elevation[i],global.i),global.e);
  assert.equal(await page.evaluate(()=>atlas.renderer.tiles.generation),generation);
  assert.equal(await page.evaluate(()=>atlas.world.meta.statistics.meanTemperature),global.mean);
  await page.click('#undo');assert.equal(await page.evaluate(()=>atlas.world.meta.detail.edits.length),0);
  await page.click('#redo');assert.equal(await page.evaluate(()=>atlas.world.meta.detail.edits.length),1);await ready();
  console.log('Local edit/undo/redo and independent simulation passed.');
  await openLayers(page).then(()=>page.uncheck('#lod-enabled'));assert.equal(await page.evaluate(()=>atlas.renderer.tiles.workers.length),0);
  await openLayers(page).then(()=>page.check('#lod-enabled'));await ready();
  await page.evaluate(()=>{atlas.renderer.camera.x=0;atlas.renderer.draw();});await ready();
  await page.screenshot({path:'test-output/v2-wrapped-detail.png'});
